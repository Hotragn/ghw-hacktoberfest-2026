def fixture_key(device_id: str, recorded_at_iso: str) -> str:
    return f"{device_id}|{recorded_at_iso}"


def embed_text(
    summary: str,
    *,
    site: str,
    category: str,
    severity: int,
    device_id: str,
) -> list[float]:
    """Lexical hash embedding: char trigrams + per-dimension salted hashes."""
    payload = f"{site}|{category}|{severity}|{device_id}|{summary.lower().strip()}"
    vec = [0.0] * DIM
    text = summary.lower()
    for i in range(max(0, len(text) - 2)):
        tri = text[i : i + 3]
        h = hashlib.sha256(f"{payload}|tri:{tri}".encode()).digest()
        idx = h[0] % DIM
        vec[idx] += (h[1] / 127.5) - 1.0
        idx2 = h[2] % DIM
        vec[idx2] += (h[3] / 127.5) - 1.0
    for i in range(DIM):
        h = hashlib.sha256(f"{payload}|dim:{i}".encode()).digest()
        vec[i] += (int.from_bytes(h[:2], "big") / 32767.5) - 1.0
    norm = math.sqrt(sum(x * x for x in vec)) or 1.0
    return [round(x / norm, 6) for x in vec]


def vec_literal(v: list[float]) -> str:
    return "[" + ",".join(f"{x:.6f}" for x in v) + "]"


def sql_ts(iso: str) -> str:
    return iso.replace("T", " ").replace("+00:00", "+00")


def write_outputs() -> dict[str, list[float]]:
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    vectors_by_summary: dict[str, list[float]] = {}
    sql_lines = [
        "-- Generated by scripts/gen_deterministic_embeddings.py — do not hand-edit.",
        "-- No DELETE: idempotent INSERT ON CONFLICT DO NOTHING.",
        "SET search_path TO builders_week, public;",
        "",
        "INSERT INTO alert_embeddings",
        "  (recorded_at, fixture_key, device_id, site, category, severity, summary_text, tags, embedding, fixture_batch)",
        "VALUES",
    ]
    value_rows: list[str] = []

    with OUT_CSV.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(
            [
                "recorded_at",
                "fixture_key",
                "device_id",
                "site",
                "category",
                "severity",
                "summary_text",
                "tags",
                "embedding",
                "fixture_batch",
            ]
        )
        for ts, dev, site, cat, sev, summary, tags in ROWS:
            fkey = fixture_key(dev, ts)
            tags_list = tags.split(",")
            emb = embed_text(summary, site=site, category=cat, severity=sev, device_id=dev)
            vectors_by_summary[summary] = emb
            w.writerow([ts, fkey, dev, site, cat, sev, summary, ";".join(tags_list), vec_literal(emb), FIXTURE_BATCH])
            value_rows.append(
                f"  ('{sql_ts(ts)}', '{fkey}', '{dev}', '{site}', '{cat}', {sev}, "
                f"{summary!r}, ARRAY{tags_list!r}, '{vec_literal(emb)}'::vector(256), '{FIXTURE_BATCH}')"
            )

    sql_lines.append(",\n".join(value_rows))
    sql_lines.append(
        "ON CONFLICT (recorded_at, fixture_key) DO NOTHING;"
    )
    OUT_SQL.write_text("\n".join(sql_lines) + "\n", encoding="utf-8")

    query_vectors = {
        "_note": "NON-SEMANTIC 256-d lexical hashes for similarity demo queries",
        "thermal_critical_reference": vec_literal(
            embed_text(
                "high temperature alert threshold exceeded",
                site="lab-east",
                category="thermal",
                severity=5,
                device_id="sensor-a1",
            )
        ),
        "cooling_fan_reference": vec_literal(
            embed_text(
                "cooling fan failure suspected",
                site="lab-east",
                category="thermal",
                severity=5,
                device_id="sensor-a1",
            )
        ),
        "soft_warning_reference": vec_literal(
            embed_text(
                "soft warning below critical threshold",
                site="lab-east",
                category="thermal",
                severity=3,
                device_id="sensor-a1",
            )
        ),
    }
    OUT_QUERY_JSON.write_text(json.dumps(query_vectors, indent=2) + "\n", encoding="utf-8")
    _write_query_sql_files(query_vectors)
    return vectors_by_summary


def _write_query_sql_files(qv: dict[str, str]) -> None:
    qdir = ROOT / "queries"
    cooling = qv["cooling_fan_reference"]
    thermal = qv["thermal_critical_reference"]
    soft = qv["soft_warning_reference"]
    (qdir / "similarity_cosine.sql").write_text(
        f"""-- Generated vector literals — NON-SEMANTIC 256-d lexical demo.
SET search_path TO builders_week, public;

WITH q AS (
  SELECT '{cooling}'::vector(256) AS query_vec
)
SELECT
  a.recorded_at,
  a.site,
  a.category,
  a.severity,
  a.summary_text,
  (a.embedding <=> q.query_vec) AS cosine_distance,
  (1 - (a.embedding <=> q.query_vec))::double precision AS cosine_similarity
FROM alert_embeddings a, q
ORDER BY a.embedding <=> q.query_vec
LIMIT 5;
""",
        encoding="utf-8",
    )
    (qdir / "similarity_l2.sql").write_text(
        f"""SET search_path TO builders_week, public;

WITH q AS (
  SELECT '{cooling}'::vector(256) AS query_vec
)
SELECT
  a.recorded_at,
  a.site,
  a.summary_text,
  (a.embedding <-> q.query_vec) AS l2_distance
FROM alert_embeddings a, q
ORDER BY a.embedding <-> q.query_vec
LIMIT 5;
""",
        encoding="utf-8",
    )
    (qdir / "similarity_filtered_time.sql").write_text(
        f"""SET search_path TO builders_week, public;

WITH q AS (
  SELECT '{thermal}'::vector(256) AS query_vec
)
SELECT
  a.recorded_at,
  a.device_id,
  a.summary_text,
  (a.embedding <=> q.query_vec) AS cosine_distance
FROM alert_embeddings a, q
WHERE a.recorded_at >= TIMESTAMPTZ '2026-11-02 00:00:00+00'
  AND a.recorded_at <  TIMESTAMPTZ '2026-11-03 00:00:00+00'
ORDER BY a.embedding <=> q.query_vec
LIMIT 5;
""",
        encoding="utf-8",
    )
    (qdir / "similarity_filtered_metadata.sql").write_text(
        f"""SET search_path TO builders_week, public;

WITH q AS (
  SELECT '{soft}'::vector(256) AS query_vec
)
SELECT
  a.recorded_at,
  a.site,
  a.severity,
  a.tags,
  a.summary_text,
  (a.embedding <=> q.query_vec) AS cosine_distance
FROM alert_embeddings a, q
WHERE a.site = 'lab-east'
  AND a.severity >= 3
  AND 'thermal' = ANY (a.tags)
  AND (a.embedding <=> q.query_vec) < 0.85
ORDER BY a.embedding <=> q.query_vec
LIMIT 10;
""",
        encoding="utf-8",
    )
    (qdir / "join_timeseries_vector.sql").write_text(
        f"""-- Closest alert in ±6h window by vector distance (cosine), not earliest timestamp.
SET search_path TO builders_week, public;

WITH q AS (
  SELECT '{thermal}'::vector(256) AS query_vec
)
SELECT
  d.recorded_at,
  d.device_id,
  d.event_type,
  d.message AS event_message,
  a.summary_text AS closest_alert_by_vector_distance,
  a.cosine_distance
FROM device_events d
CROSS JOIN q
LEFT JOIN LATERAL (
  SELECT
    ae.summary_text,
  (ae.embedding <=> q.query_vec) AS cosine_distance
  FROM alert_embeddings ae
  WHERE ae.device_id = d.device_id
    AND ae.recorded_at >= d.recorded_at - INTERVAL '6 hours'
    AND ae.recorded_at <= d.recorded_at + INTERVAL '6 hours'
  ORDER BY ae.embedding <=> q.query_vec, ae.recorded_at
  LIMIT 1
) a ON TRUE
WHERE d.severity >= 3
  AND d.fixture_batch = 'bw2026-demo-v1'
ORDER BY d.recorded_at
LIMIT 15;
""",
        encoding="utf-8",
    )


def main() -> int:
    write_outputs()
    print(f"Wrote {OUT_CSV}", file=sys.stderr)
    print(f"Wrote {OUT_SQL}", file=sys.stderr)
    print(f"Wrote {OUT_QUERY_JSON}", file=sys.stderr)
    if "--print-sql" in sys.argv:
        print(OUT_SQL.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
