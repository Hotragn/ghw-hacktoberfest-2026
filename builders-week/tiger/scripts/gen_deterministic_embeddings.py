"""256-d deterministic **lexical feature hashing** for pgvector demo SQL.

NON-SEMANTIC: does not invoke any ML model or external API. Same text/metadata always
yields the same unit vector. Suitable for operator/index/filter exercises only — not
AI semantic embedding or RAG completion.

Outputs (default):
  data/alert_embeddings_sample.csv
  sql/04b_import_alert_embeddings.sql
  data/query_vectors.json
"""
